#!/usr/bin/env node
// The live view's vault and passkey dialog look like the rbw extension: its
// palette and type come from rbw's browser/extension/theme.css and its icon
// from icons/rbw-48.png, both from the flake input `rbw`.
//
//   node tools/rbw-theme.mjs sync RBW_SRC    rewrite handoff.html from rbw
//   node tools/rbw-theme.mjs check RBW_SRC   fail when handoff.html differs
//
// `just rbw-theme` syncs from the locked input; `nix flake check` checks it.
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const HANDOFF = new URL('../handoff.html', import.meta.url);
const BEGIN = '  /* rbw-theme:begin (generated by tools/rbw-theme.mjs from rbw\'s theme.css; do not edit) */\n';
const END = '  /* rbw-theme:end */\n';
const ICON = /(<img class="rbw-ic" alt="" src="data:image\/png;base64,)[^"]*(")/;

// theme.css is two rules: light on :root, dark on :root[data-theme=dark].
function parseTheme(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const rules = {};
  const rest = css.replace(/(:root(?:\[data-theme=dark\])?)\s*\{([^}]*)\}/g, (_, selector, body) => {
    rules[selector] = body.split(';').map((d) => d.trim().replace(/\s+/g, ' ')).filter(Boolean);
    return '';
  });
  if (rest.trim() || !rules[':root'] || !rules[':root[data-theme=dark]']) {
    throw new Error('theme.css must hold exactly a :root and a :root[data-theme=dark] rule');
  }
  // In rbw the dark rule cascades over :root; here it stands alone, so it
  // carries :root's declarations (the font) with dark's on top.
  const property = (d) => d.slice(0, d.indexOf(':')).trim();
  const merged = new Map(rules[':root'].map((d) => [property(d), d]));
  for (const d of rules[':root[data-theme=dark]']) merged.set(property(d), d);
  return {light: rules[':root'], dark: [...merged.values()]};
}

// The live view is dark unless its theme (or, on "system", the OS) says light.
function themeBlock({light, dark}) {
  const decls = (list) => list.join('; ') + ';';
  return BEGIN
    + `  .rbw-surface { ${decls(dark)} }\n`
    + '  @media (prefers-color-scheme: light) {\n'
    + `    :root:not([data-theme="dark"]) .rbw-surface { ${decls(light)} }\n`
    + '  }\n'
    + `  :root[data-theme="light"] .rbw-surface { ${decls(light)} }\n`
    + END;
}

function render(html, src) {
  const theme = parseTheme(readFileSync(join(src, 'browser/extension/theme.css'), 'utf8'));
  const icon = readFileSync(join(src, 'browser/extension/icons/rbw-48.png')).toString('base64');
  const start = html.indexOf(BEGIN), end = html.indexOf(END);
  if (start < 0 || end < start) throw new Error('handoff.html lacks the rbw-theme markers');
  html = html.slice(0, start) + themeBlock(theme) + html.slice(end + END.length);
  if (!ICON.test(html)) throw new Error('handoff.html lacks the rbw icon');
  return html.replace(ICON, `$1${icon}$2`);
}

const [mode, src] = process.argv.slice(2);
if (!['sync', 'check'].includes(mode) || !src) {
  console.error('usage: rbw-theme.mjs sync|check RBW_SRC');
  process.exit(2);
}
const html = readFileSync(HANDOFF, 'utf8');
const want = render(html, src);
if (mode === 'sync') {
  if (want !== html) writeFileSync(HANDOFF, want);
  console.log(want === html ? 'handoff.html already matches rbw' : 'handoff.html updated from rbw');
} else if (want !== html) {
  console.error('handoff.html differs from the locked rbw theme: run `just rbw-theme`');
  process.exit(1);
}
