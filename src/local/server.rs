#[derive(Debug, Deserialize)]
struct OpenRequest {
    url: String,
    /// The browser to open it in (default: the first one connected).
    #[serde(default)]
    client: Option<String>,
    /// Do not bring it to the front.
    #[serde(default)]
    background: bool,
}

async fn open_tab(
    State(app): State<App>,
    ConnectInfo(peer): ConnectInfo<Peer>,
    method: Method,
    uri: Uri,
    headers: HeaderMap,
    Json(req): Json<OpenRequest>,
) -> Response {
    if let Some(res) = app.reject(&headers, "tabs:control", &peer, &method, &uri) {
        return res;
    }
    if !(req.url.starts_with("http://") || req.url.starts_with("https://")) {
        return error(StatusCode::BAD_REQUEST, "only http and https URLs open");
    }
    let client = match req.client {
        Some(c) => c,
        None => {
            let t = app.tabs.lock().expect("tabs");
            match t.sorted_clients().first() {
                Some(c) => c.prefix.clone(),
                None => return error(StatusCode::NOT_FOUND, "no browser is connected"),
            }
        }
    };
    let cmd = json!({"action": "open", "url": req.url, "background": req.background});
    match command(&app, &client, cmd).await {
        Ok(result) => {
            Json(json!({"ok": true, "id": format!("{client}:{}", result["tab"])})).into_response()
        }
        Err(failure) => respond(failure),
    }
}

fn router(app: App) -> Router {
    Router::new()
        .route("/v1/tabs", get(list_tabs))
        .route("/v1/tabs/{id}", get(get_tab))
        .route("/v1/windows", get(list_windows))
        .route("/v1/clients", get(list_clients))
        .route("/v1/tabs/{id}/activate", post(activate_tab))
        .route("/v1/tabs/{id}/close", post(close_tab))
        .route("/v1/tabs/open", post(open_tab))
        .with_state(app)
}

/// One native host: a `hello`, then snapshots, one JSON object per line.
async fn feed(stream: UnixStream, tabs: Arc<Mutex<Tabs>>) {
    // SAFETY: getuid cannot fail.
    let uid = unsafe { libc::getuid() };
    match stream.peer_cred() {
        Ok(cred) if cred.uid() == uid => {}
        Ok(cred) => {
            tracing::warn!(uid = cred.uid(), "refusing a feeder of another user");
            return;
        }
        Err(e) => {
            tracing::warn!("refusing a feeder: {e}");
            return;
        }
    }
    let (read, mut write) = stream.into_split();
    let (outbound, mut to_host) = mpsc::unbounded_channel::<String>();
    let conn = {
        let mut t = tabs.lock().expect("tabs");
        t.next_conn += 1;
        let conn = t.next_conn;
        t.outbound.insert(conn, outbound);
        conn
    };
    tokio::spawn(async move {
        while let Some(line) = to_host.recv().await {
            if write
                .write_all(format!("{line}\n").as_bytes())
                .await
                .is_err()
            {
                break;
            }
        }
    });
    let mut lines = BufReader::new(read).lines();
    loop {
        let line = match lines.next_line().await {
            Ok(Some(line)) => line,
            Ok(None) => break,
            Err(e) => {
                tracing::warn!("feeder {conn}: {e}");
                break;
            }
        };
        // The extension's answer to a command (see `command`).
        if let Ok(value) = serde_json::from_str::<Value>(&line) {
            if value["type"] == "result" {
                let waiting = value["id"]
                    .as_u64()
                    .and_then(|id| tabs.lock().expect("tabs").pending.remove(&id));
                if let Some(waiting) = waiting {
                    let _ = waiting.send(value);
                }
                continue;
            }
        }
        let msg: Feed = match serde_json::from_str(&line) {
            Ok(m) => m,
            Err(e) => {
                tracing::debug!("feeder {conn}: ignoring a message: {e}");
                continue;
            }
        };
        let mut t = tabs.lock().expect("tabs");
        match msg {
            Feed::Hello {
                browser,
                profile,
                name,
                version,
                label,
            } => {
                let prefix = t.name_for(&profile, &label, &browser);
                tracing::info!("{browser} ({name} {version}) connected as {prefix}");
                let now = now();
                t.clients.insert(
                    conn,
                    Client {
                        prefix,
                        browser,
                        profile,
                        name,
                        version,
                        connected: now,
                        updated: now,
                        windows: Vec::new(),
                        tabs: Vec::new(),
                    },
                );
            }
            Feed::Snapshot {
                windows,
                tabs: list,
            } => match t.clients.get_mut(&conn) {
                Some(c) => {
                    c.windows = windows;
                    c.tabs = list;
                    c.updated = now();
                }
                None => tracing::debug!("feeder {conn}: snapshot before hello"),
            },
        }
    }
    tabs.lock().expect("tabs").outbound.remove(&conn);
    if let Some(c) = tabs.lock().expect("tabs").clients.remove(&conn) {
        tracing::info!("{} ({}) disconnected", c.prefix, c.browser);
    }
}

/// Sockets systemd passed (`LISTEN_FDS`), by `FileDescriptorName=`.
fn activated() -> HashMap<String, std::os::unix::net::UnixListener> {
    use std::os::fd::FromRawFd;
    let mut out = HashMap::new();
    let pid_matches = std::env::var("LISTEN_PID")
        .ok()
        .and_then(|p| p.parse::<u32>().ok())
        == Some(std::process::id());
    let count = std::env::var("LISTEN_FDS")
        .ok()
        .and_then(|n| n.parse::<i32>().ok())
        .unwrap_or(0);
    if !pid_matches || count <= 0 {
        return out;
    }
    let names: Vec<String> = std::env::var("LISTEN_FDNAMES")
        .unwrap_or_default()
        .split(':')
        .map(str::to_owned)
        .collect();
    for i in 0..count {
        let fd = 3 + i;
        let name = names.get(i as usize).cloned().unwrap_or_default();
        // SAFETY: systemd passes these descriptors to this process, once.
        let listener = unsafe { std::os::unix::net::UnixListener::from_raw_fd(fd) };
        out.insert(name, listener);
    }
    for var in ["LISTEN_PID", "LISTEN_FDS", "LISTEN_FDNAMES"] {
        std::env::remove_var(var);
    }
    out
}

/// A private directory for the sockets: ours, mode 0700.
fn private_dir(dir: &Path) -> R<()> {
    std::fs::DirBuilder::new()
        .recursive(true)
        .mode(0o700)
        .create(dir)?;
    let meta = std::fs::metadata(dir)?;
    // SAFETY: getuid cannot fail.
    if meta.uid() != unsafe { libc::getuid() } {
        return Err(format!("{} belongs to another user", dir.display()).into());
    }
    if meta.mode() & 0o077 != 0 {
        std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700))?;
    }
    Ok(())
}

fn bind(path: &Path) -> R<UnixListener> {
    if let Some(dir) = path.parent() {
        private_dir(dir)?;
    }
    if path.exists() {
        if std::os::unix::net::UnixStream::connect(path).is_ok() {
            return Err(format!("a server already listens on {}", path.display()).into());
        }
        std::fs::remove_file(path)?;
    }
    let listener = UnixListener::bind(path)?;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))?;
    Ok(listener)
}

fn listener(
    activated: &mut HashMap<String, std::os::unix::net::UnixListener>,
    name: &str,
    path: &Path,
) -> R<UnixListener> {
    match activated.remove(name) {
        Some(l) => {
            l.set_nonblocking(true)?;
            Ok(UnixListener::from_std(l)?)
        }
        None => bind(path),
    }
}

pub async fn serve(args: ServeArgs) -> R<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "browser_daemon=info".into()),
        )
        .init();
    let mut sockets = activated();
    let api_path = args.api_socket.unwrap_or_else(super::api_socket);
    let feeder_path = args.feeder_socket.unwrap_or_else(super::feeder_socket);
    let api = listener(&mut sockets, "api", &api_path)?;
    let feeder = listener(&mut sockets, "feeder", &feeder_path)?;

    let mut files = vec![args.token_file];
    files.extend(args.token_configs);
    let store = Store::new(files);
    if store.len() == 0 {
        tracing::warn!("no tokens yet: every request is refused until `browser-daemon local token create` makes one");
    }
    let app = App {
        tabs: Arc::new(Mutex::new(Tabs::default())),
        tokens: Arc::new(Mutex::new(store)),
    };

    let tabs = app.tabs.clone();
    tokio::spawn(async move {
        loop {
            match feeder.accept().await {
                Ok((stream, _)) => {
                    tokio::spawn(feed(stream, tabs.clone()));
                }
                Err(e) => tracing::warn!("feeder accept: {e}"),
            }
        }
    });

    tracing::info!("local API on {}", api_path.display());
    let service = router(app).into_make_service_with_connect_info::<Peer>();
    axum::serve(api, service)
        .with_graceful_shutdown(async {
            let _ = tokio::signal::ctrl_c().await;
        })
        .await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn client(prefix: &str, tabs: Vec<Tab>, windows: Vec<Window>) -> Client {
        Client {
            prefix: prefix.into(),
            browser: "firefox".into(),
            profile: prefix.into(),
            name: "Firefox".into(),
            version: "1".into(),
            connected: 0,
            updated: 0,
            windows,
            tabs,
        }
    }

    #[test]
    fn names_clients_after_the_host_and_browser_or_their_label() {
        let mut t = Tabs::default();
        let firefox = format!("{}-firefox", slug(&host_name()));
        assert_eq!(t.name_for("p1", "", "firefox"), firefox);
        assert_eq!(t.name_for("p2", "", "firefox"), format!("{firefox}-2"));
        assert_eq!(t.name_for("p1", "", "firefox"), firefox);
        assert_eq!(
            t.name_for("p3", "Work Chromium!", "chromium"),
            "work-chromium"
        );
        assert_eq!(slug("--"), "browser");
    }

    #[test]
    fn lists_and_filters_tabs() {
        let mut t = Tabs::default();
        let tab = |id, window_id, index, url: &str, audible| Tab {
            id,
            window_id,
            index,
            title: format!("T{id}"),
            url: url.into(),
            audible,
            ..Tab::default()
        };
        t.clients.insert(
            1,
            client(
                "a",
                vec![
                    tab(7, 1, 1, "https://meet.jit.si/x", false),
                    tab(5, 1, 0, "https://example.com/", true),
                ],
                vec![Window {
                    id: 1,
                    focused: true,
                }],
            ),
        );
        let views = tab_views(&t);
        assert_eq!(views[0].id, "a:5");
        assert!(views[0].focused_window);
        let audible = TabFilter {
            audible: Some(true),
            ..TabFilter::default()
        };
        assert_eq!(views.iter().filter(|v| audible.matches(v)).count(), 1);
        let url = TabFilter {
            url: Some("MEET.JIT.SI".into()),
            ..TabFilter::default()
        };
        let hits: Vec<_> = views.iter().filter(|v| url.matches(v)).collect();
        assert_eq!(hits.len(), 1);
        assert_eq!(hits[0].id, "a:7");
    }
}
