#[derive(Args, Debug)]
pub struct ServeArgs {
    /// The API socket (default: $XDG_RUNTIME_DIR/browser-daemon/local.sock).
    #[arg(long)]
    api_socket: Option<PathBuf>,
    /// The socket native hosts connect to.
    #[arg(long)]
    feeder_socket: Option<PathBuf>,
    /// The token file `local token` manages.
    #[arg(long, default_value_os_t = tokens::default_file())]
    token_file: PathBuf,
    /// More, read-only token files (for example generated by Nix). Repeatable.
    #[arg(long = "token-config")]
    token_configs: Vec<PathBuf>,
}

/// One connected browser profile.
#[derive(Debug, Clone)]
struct Client {
    prefix: String,
    browser: String,
    profile: String,
    name: String,
    version: String,
    connected: u64,
    updated: u64,
    windows: Vec<Window>,
    tabs: Vec<Tab>,
}

#[derive(Default)]
struct Tabs {
    /// By connection.
    clients: BTreeMap<u64, Client>,
    /// A profile keeps its prefix across reconnects while the server runs.
    prefixes: HashMap<String, String>,
    next_conn: u64,
}

fn now() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

/// a, b, ..., z, aa, ab, ...
fn prefix_name(mut n: usize) -> String {
    let mut s = Vec::new();
    loop {
        s.push(b'a' + (n % 26) as u8);
        if n < 26 {
            break;
        }
        n = n / 26 - 1;
    }
    s.reverse();
    String::from_utf8(s).unwrap_or_default()
}

impl Tabs {
    fn prefix_for(&mut self, profile: &str) -> String {
        if let Some(p) = self.prefixes.get(profile) {
            return p.clone();
        }
        let taken: Vec<&String> = self.prefixes.values().collect();
        let p = (0..)
            .map(prefix_name)
            .find(|p| !taken.contains(&p))
            .unwrap_or_default();
        self.prefixes.insert(profile.to_owned(), p.clone());
        p
    }

    fn sorted_clients(&self) -> Vec<&Client> {
        let mut clients: Vec<&Client> = self.clients.values().collect();
        clients.sort_by(|a, b| {
            a.prefix
                .len()
                .cmp(&b.prefix.len())
                .then(a.prefix.cmp(&b.prefix))
        });
        clients
    }
}

/// A tab as the API shows it: `id` is `<prefix>.<window>.<tab>`.
#[derive(Debug, Serialize, PartialEq)]
pub struct TabView {
    pub id: String,
    pub client: String,
    pub browser: String,
    pub window_id: i64,
    pub tab_id: i64,
    pub index: i64,
    pub title: String,
    pub url: String,
    pub active: bool,
    pub audible: bool,
    pub muted: bool,
    pub pinned: bool,
    pub discarded: bool,
    pub focused_window: bool,
    pub favicon: String,
}

#[derive(Debug, Default, Deserialize)]
pub struct TabFilter {
    pub audible: Option<bool>,
    pub active: Option<bool>,
    pub pinned: Option<bool>,
    pub muted: Option<bool>,
    pub browser: Option<String>,
    pub client: Option<String>,
    pub window: Option<i64>,
    /// Case-insensitive substring of the URL.
    pub url: Option<String>,
    /// Case-insensitive substring of the title.
    pub title: Option<String>,
    /// Case-insensitive substring of the title or the URL.
    pub q: Option<String>,
}

fn contains(haystack: &str, needle: &Option<String>) -> bool {
    needle
        .as_ref()
        .is_none_or(|n| haystack.to_lowercase().contains(&n.to_lowercase()))
}

impl TabFilter {
    fn matches(&self, t: &TabView) -> bool {
        self.audible.is_none_or(|v| t.audible == v)
            && self.active.is_none_or(|v| t.active == v)
            && self.pinned.is_none_or(|v| t.pinned == v)
            && self.muted.is_none_or(|v| t.muted == v)
            && self.window.is_none_or(|v| t.window_id == v)
            && self.browser.as_ref().is_none_or(|b| t.browser == *b)
            && self.client.as_ref().is_none_or(|c| t.client == *c)
            && contains(&t.url, &self.url)
            && contains(&t.title, &self.title)
            && self.q.as_ref().is_none_or(|q| {
                let q = q.to_lowercase();
                t.title.to_lowercase().contains(&q) || t.url.to_lowercase().contains(&q)
            })
    }
}

fn tab_views(tabs: &Tabs) -> Vec<TabView> {
    let mut out = Vec::new();
    for c in tabs.sorted_clients() {
        let mut list: Vec<&Tab> = c.tabs.iter().collect();
        list.sort_by_key(|t| (t.window_id, t.index));
        for t in list {
            let focused = c.windows.iter().any(|w| w.id == t.window_id && w.focused);
            out.push(TabView {
                id: format!("{}.{}.{}", c.prefix, t.window_id, t.id),
                client: c.prefix.clone(),
                browser: c.browser.clone(),
                window_id: t.window_id,
                tab_id: t.id,
                index: t.index,
                title: t.title.clone(),
                url: t.url.clone(),
                active: t.active,
                audible: t.audible,
                muted: t.muted,
                pinned: t.pinned,
                discarded: t.discarded,
                focused_window: focused,
                favicon: t.favicon.clone(),
            });
        }
    }
    out
}

#[derive(Clone)]
struct App {
    tabs: Arc<Mutex<Tabs>>,
    tokens: Arc<Mutex<Store>>,
}

/// Who is on the other end of an API connection.
#[derive(Clone, Debug)]
struct Peer {
    pid: Option<i32>,
}

impl Connected<axum::serve::IncomingStream<'_, UnixListener>> for Peer {
    fn connect_info(stream: axum::serve::IncomingStream<'_, UnixListener>) -> Self {
        Peer {
            pid: stream.io().peer_cred().ok().and_then(|c| c.pid()),
        }
    }
}

fn error(status: StatusCode, msg: &str) -> Response {
    let mut res = (status, Json(json!({"error": msg}))).into_response();
    if status == StatusCode::UNAUTHORIZED {
        res.headers_mut()
            .insert(header::WWW_AUTHENTICATE, "Bearer".parse().expect("static"));
    }
    res
}

impl App {
    /// `None` when the request's token has `scope`, else the response
    /// refusing it. Logs either way.
    fn reject(
        &self,
        headers: &HeaderMap,
        scope: &str,
        peer: &Peer,
        method: &Method,
        uri: &Uri,
    ) -> Option<Response> {
        let header = headers
            .get(header::AUTHORIZATION)
            .and_then(|v| v.to_str().ok());
        let result = self
            .tokens
            .lock()
            .expect("token store")
            .authorize(header, scope);
        match result {
            Ok(id) => {
                tracing::info!(token = %id.name, pid = ?peer.pid, "{method} {uri}");
                None
            }
            Err(Denied::Unauthorized) => {
                tracing::warn!(pid = ?peer.pid, "unauthorized: {method} {uri}");
                Some(error(StatusCode::UNAUTHORIZED, "a valid token is required"))
            }
            Err(Denied::Forbidden(name)) => {
                tracing::warn!(token = %name, pid = ?peer.pid, "forbidden ({scope}): {method} {uri}");
                Some(error(
                    StatusCode::FORBIDDEN,
                    &format!("this token lacks the {scope} scope"),
                ))
            }
        }
    }
}

async fn list_tabs(
    State(app): State<App>,
    ConnectInfo(peer): ConnectInfo<Peer>,
    method: Method,
    uri: Uri,
    headers: HeaderMap,
    Query(filter): Query<TabFilter>,
) -> Response {
    if let Some(res) = app.reject(&headers, "tabs:read", &peer, &method, &uri) {
        return res;
    }
    let tabs = app.tabs.lock().expect("tabs");
    let list: Vec<TabView> = tab_views(&tabs)
        .into_iter()
        .filter(|t| filter.matches(t))
        .collect();
    Json(list).into_response()
}

async fn get_tab(
    State(app): State<App>,
    ConnectInfo(peer): ConnectInfo<Peer>,
    method: Method,
    uri: Uri,
    headers: HeaderMap,
    UrlPath(id): UrlPath<String>,
) -> Response {
    if let Some(res) = app.reject(&headers, "tabs:read", &peer, &method, &uri) {
        return res;
    }
    let tabs = app.tabs.lock().expect("tabs");
    match tab_views(&tabs).into_iter().find(|t| t.id == id) {
        Some(t) => Json(t).into_response(),
        None => error(StatusCode::NOT_FOUND, "no such tab"),
    }
}

async fn list_windows(
    State(app): State<App>,
    ConnectInfo(peer): ConnectInfo<Peer>,
    method: Method,
    uri: Uri,
    headers: HeaderMap,
) -> Response {
    if let Some(res) = app.reject(&headers, "tabs:read", &peer, &method, &uri) {
        return res;
    }
    let tabs = app.tabs.lock().expect("tabs");
    let mut out = Vec::new();
    for c in tabs.sorted_clients() {
        let mut windows = c.windows.clone();
        windows.sort_by_key(|w| w.id);
        for w in windows {
            let in_window: Vec<&Tab> = c.tabs.iter().filter(|t| t.window_id == w.id).collect();
            let active = in_window
                .iter()
                .find(|t| t.active)
                .map(|t| format!("{}.{}.{}", c.prefix, w.id, t.id));
            out.push(json!({
                "id": format!("{}.{}", c.prefix, w.id),
                "client": c.prefix,
                "browser": c.browser,
                "window_id": w.id,
                "focused": w.focused,
                "tabs": in_window.len(),
                "active_tab": active,
            }));
        }
    }
    Json(out).into_response()
}

async fn list_clients(
    State(app): State<App>,
    ConnectInfo(peer): ConnectInfo<Peer>,
    method: Method,
    uri: Uri,
    headers: HeaderMap,
) -> Response {
    if let Some(res) = app.reject(&headers, "tabs:read", &peer, &method, &uri) {
        return res;
    }
    let tabs = app.tabs.lock().expect("tabs");
    let out: Vec<_> = tabs
        .sorted_clients()
        .into_iter()
        .map(|c| {
            json!({
                "prefix": c.prefix,
                "browser": c.browser,
                "name": c.name,
                "version": c.version,
                "profile": c.profile,
                "windows": c.windows.len(),
                "tabs": c.tabs.len(),
                "connected": c.connected,
                "updated": c.updated,
            })
        })
        .collect();
    Json(out).into_response()
}

fn router(app: App) -> Router {
    Router::new()
        .route("/v1/tabs", get(list_tabs))
        .route("/v1/tabs/{id}", get(get_tab))
        .route("/v1/windows", get(list_windows))
        .route("/v1/clients", get(list_clients))
        .with_state(app)
}

/// One native host: a `hello`, then snapshots, one JSON object per line.
async fn feed(stream: UnixStream, tabs: Arc<Mutex<Tabs>>) {
    // SAFETY: getuid cannot fail.
    let uid = unsafe { libc::getuid() };
    match stream.peer_cred() {
        Ok(cred) if cred.uid() == uid => {}
        Ok(cred) => {
            tracing::warn!(uid = cred.uid(), "refusing a feeder of another user");
            return;
        }
        Err(e) => {
            tracing::warn!("refusing a feeder: {e}");
            return;
        }
    }
    let conn = {
        let mut t = tabs.lock().expect("tabs");
        t.next_conn += 1;
        t.next_conn
    };
    let mut lines = BufReader::new(stream).lines();
    loop {
        let line = match lines.next_line().await {
            Ok(Some(line)) => line,
            Ok(None) => break,
            Err(e) => {
                tracing::warn!("feeder {conn}: {e}");
                break;
            }
        };
        let msg: Feed = match serde_json::from_str(&line) {
            Ok(m) => m,
            Err(e) => {
                tracing::debug!("feeder {conn}: ignoring a message: {e}");
                continue;
            }
        };
        let mut t = tabs.lock().expect("tabs");
        match msg {
            Feed::Hello {
                browser,
                profile,
                name,
                version,
            } => {
                let prefix = t.prefix_for(&profile);
                tracing::info!("{browser} ({name} {version}) connected as {prefix}");
                let now = now();
                t.clients.insert(
                    conn,
                    Client {
                        prefix,
                        browser,
                        profile,
                        name,
                        version,
                        connected: now,
                        updated: now,
                        windows: Vec::new(),
                        tabs: Vec::new(),
                    },
                );
            }
            Feed::Snapshot {
                windows,
                tabs: list,
            } => match t.clients.get_mut(&conn) {
                Some(c) => {
                    c.windows = windows;
                    c.tabs = list;
                    c.updated = now();
                }
                None => tracing::debug!("feeder {conn}: snapshot before hello"),
            },
        }
    }
    if let Some(c) = tabs.lock().expect("tabs").clients.remove(&conn) {
        tracing::info!("{} ({}) disconnected", c.prefix, c.browser);
    }
}

/// Sockets systemd passed (`LISTEN_FDS`), by `FileDescriptorName=`.
fn activated() -> HashMap<String, std::os::unix::net::UnixListener> {
    use std::os::fd::FromRawFd;
    let mut out = HashMap::new();
    let pid_matches = std::env::var("LISTEN_PID")
        .ok()
        .and_then(|p| p.parse::<u32>().ok())
        == Some(std::process::id());
    let count = std::env::var("LISTEN_FDS")
        .ok()
        .and_then(|n| n.parse::<i32>().ok())
        .unwrap_or(0);
    if !pid_matches || count <= 0 {
        return out;
    }
    let names: Vec<String> = std::env::var("LISTEN_FDNAMES")
        .unwrap_or_default()
        .split(':')
        .map(str::to_owned)
        .collect();
    for i in 0..count {
        let fd = 3 + i;
        let name = names.get(i as usize).cloned().unwrap_or_default();
        // SAFETY: systemd passes these descriptors to this process, once.
        let listener = unsafe { std::os::unix::net::UnixListener::from_raw_fd(fd) };
        out.insert(name, listener);
    }
    for var in ["LISTEN_PID", "LISTEN_FDS", "LISTEN_FDNAMES"] {
        std::env::remove_var(var);
    }
    out
}

/// A private directory for the sockets: ours, mode 0700.
fn private_dir(dir: &Path) -> R<()> {
    std::fs::DirBuilder::new()
        .recursive(true)
        .mode(0o700)
        .create(dir)?;
    let meta = std::fs::metadata(dir)?;
    // SAFETY: getuid cannot fail.
    if meta.uid() != unsafe { libc::getuid() } {
        return Err(format!("{} belongs to another user", dir.display()).into());
    }
    if meta.mode() & 0o077 != 0 {
        std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700))?;
    }
    Ok(())
}

fn bind(path: &Path) -> R<UnixListener> {
    if let Some(dir) = path.parent() {
        private_dir(dir)?;
    }
    if path.exists() {
        if std::os::unix::net::UnixStream::connect(path).is_ok() {
            return Err(format!("a server already listens on {}", path.display()).into());
        }
        std::fs::remove_file(path)?;
    }
    let listener = UnixListener::bind(path)?;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))?;
    Ok(listener)
}

fn listener(
    activated: &mut HashMap<String, std::os::unix::net::UnixListener>,
    name: &str,
    path: &Path,
) -> R<UnixListener> {
    match activated.remove(name) {
        Some(l) => {
            l.set_nonblocking(true)?;
            Ok(UnixListener::from_std(l)?)
        }
        None => bind(path),
    }
}

pub async fn serve(args: ServeArgs) -> R<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "browser_daemon=info".into()),
        )
        .init();
    let mut sockets = activated();
    let api_path = args.api_socket.unwrap_or_else(super::api_socket);
    let feeder_path = args.feeder_socket.unwrap_or_else(super::feeder_socket);
    let api = listener(&mut sockets, "api", &api_path)?;
    let feeder = listener(&mut sockets, "feeder", &feeder_path)?;

    let mut files = vec![args.token_file];
    files.extend(args.token_configs);
    let store = Store::new(files);
    if store.len() == 0 {
        tracing::warn!("no tokens yet: every request is refused until `browser-daemon local token create` makes one");
    }
    let app = App {
        tabs: Arc::new(Mutex::new(Tabs::default())),
        tokens: Arc::new(Mutex::new(store)),
    };

    let tabs = app.tabs.clone();
    tokio::spawn(async move {
        loop {
            match feeder.accept().await {
                Ok((stream, _)) => {
                    tokio::spawn(feed(stream, tabs.clone()));
                }
                Err(e) => tracing::warn!("feeder accept: {e}"),
            }
        }
    });

    tracing::info!("local API on {}", api_path.display());
    let service = router(app).into_make_service_with_connect_info::<Peer>();
    axum::serve(api, service)
        .with_graceful_shutdown(async {
            let _ = tokio::signal::ctrl_c().await;
        })
        .await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn client(prefix: &str, tabs: Vec<Tab>, windows: Vec<Window>) -> Client {
        Client {
            prefix: prefix.into(),
            browser: "firefox".into(),
            profile: prefix.into(),
            name: "Firefox".into(),
            version: "1".into(),
            connected: 0,
            updated: 0,
            windows,
            tabs,
        }
    }

    #[test]
    fn names_prefixes_like_spreadsheet_columns() {
        assert_eq!(prefix_name(0), "a");
        assert_eq!(prefix_name(25), "z");
        assert_eq!(prefix_name(26), "aa");
        assert_eq!(prefix_name(27), "ab");
    }

    #[test]
    fn keeps_a_profiles_prefix() {
        let mut t = Tabs::default();
        assert_eq!(t.prefix_for("p1"), "a");
        assert_eq!(t.prefix_for("p2"), "b");
        assert_eq!(t.prefix_for("p1"), "a");
    }

    #[test]
    fn lists_and_filters_tabs() {
        let mut t = Tabs::default();
        let tab = |id, window_id, index, url: &str, audible| Tab {
            id,
            window_id,
            index,
            title: format!("T{id}"),
            url: url.into(),
            audible,
            ..Tab::default()
        };
        t.clients.insert(
            1,
            client(
                "a",
                vec![
                    tab(7, 1, 1, "https://meet.jit.si/x", false),
                    tab(5, 1, 0, "https://example.com/", true),
                ],
                vec![Window {
                    id: 1,
                    focused: true,
                }],
            ),
        );
        let views = tab_views(&t);
        assert_eq!(views[0].id, "a.1.5");
        assert!(views[0].focused_window);
        let audible = TabFilter {
            audible: Some(true),
            ..TabFilter::default()
        };
        assert_eq!(views.iter().filter(|v| audible.matches(v)).count(), 1);
        let url = TabFilter {
            url: Some("MEET.JIT.SI".into()),
            ..TabFilter::default()
        };
        let hits: Vec<_> = views.iter().filter(|v| url.matches(v)).collect();
        assert_eq!(hits.len(), 1);
        assert_eq!(hits[0].id, "a.1.7");
    }
}
