//! API tokens of the local server: `bdl_<id>_<secret>`, stored as a SHA-256 of
//! the secret with a name and scopes. Every request needs one.

use std::io::Write as _;
use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt};
use std::path::{Path, PathBuf};
use std::time::SystemTime;

use clap::Subcommand;
use data_encoding::{BASE64URL_NOPAD, HEXLOWER};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use super::R;

pub const PREFIX: &str = "bdl_";

/// Every scope a token can have; see docs/local-api.md.
pub const SCOPES: [&str; 7] = [
    "tabs:read",
    "tabs:control",
    "media:control",
    "tabs:content",
    "tabs:capture",
    "tabs:debug",
    "events:read",
];

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Entry {
    pub id: String,
    pub name: String,
    pub scopes: Vec<String>,
    /// Hex SHA-256 of the secret part.
    pub sha256: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub created: Option<u64>,
}

#[derive(Debug, Default, Serialize, Deserialize)]
pub struct File {
    #[serde(default)]
    pub tokens: Vec<Entry>,
}

/// The token file `local token` manages.
pub fn default_file() -> PathBuf {
    super::config_dir().join("local-tokens.json")
}

fn random_bytes<const N: usize>() -> R<[u8; N]> {
    let mut buf = [0u8; N];
    let mut filled = 0;
    while filled < N {
        // SAFETY: writes at most N - filled bytes into buf[filled..].
        let n = unsafe { libc::getrandom(buf[filled..].as_mut_ptr().cast(), N - filled, 0) };
        if n < 0 {
            let err = std::io::Error::last_os_error();
            if err.kind() == std::io::ErrorKind::Interrupted {
                continue;
            }
            return Err(err.into());
        }
        filled += n as usize;
    }
    Ok(buf)
}

pub fn hash_secret(secret: &str) -> String {
    HEXLOWER.encode(&Sha256::digest(secret.as_bytes()))
}

/// A new token and its stored entry.
pub fn generate(name: &str, scopes: &[String]) -> R<(String, Entry)> {
    let id = HEXLOWER.encode(&random_bytes::<4>()?);
    let secret = BASE64URL_NOPAD.encode(&random_bytes::<32>()?);
    let created = SystemTime::now()
        .duration_since(SystemTime::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .ok();
    let entry = Entry {
        id: id.clone(),
        name: name.to_owned(),
        scopes: scopes.to_vec(),
        sha256: hash_secret(&secret),
        created,
    };
    Ok((format!("{PREFIX}{id}_{secret}"), entry))
}

/// `bdl_<id>_<secret>` -> (id, secret). The id is hex, so the first `_` after
/// the prefix ends it; the secret may contain `_`.
pub fn parse(token: &str) -> Option<(&str, &str)> {
    let rest = token.strip_prefix(PREFIX)?;
    let (id, secret) = rest.split_once('_')?;
    (!id.is_empty() && !secret.is_empty()).then_some((id, secret))
}

fn constant_time_eq(a: &[u8], b: &[u8]) -> bool {
    a.len() == b.len() && a.iter().zip(b).fold(0u8, |acc, (x, y)| acc | (x ^ y)) == 0
}

pub fn read_file(path: &Path) -> R<File> {
    match std::fs::read(path) {
        Ok(bytes) => {
            Ok(serde_json::from_slice(&bytes).map_err(|e| format!("{}: {e}", path.display()))?)
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(File::default()),
        Err(e) => Err(format!("{}: {e}", path.display()).into()),
    }
}

fn write_file(path: &Path, file: &File) -> R<()> {
    if let Some(dir) = path.parent() {
        std::fs::DirBuilder::new()
            .recursive(true)
            .mode(0o700)
            .create(dir)?;
    }
    let tmp = path.with_extension("json.tmp");
    let mut out = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .open(&tmp)?;
    out.write_all(&serde_json::to_vec_pretty(file)?)?;
    out.write_all(b"\n")?;
    out.sync_all()?;
    std::fs::rename(&tmp, path)?;
    Ok(())
}

/// The tokens the server accepts: the managed file plus read-only ones (for
/// example generated by Nix), reloaded when one of the files changes.
pub struct Store {
    files: Vec<PathBuf>,
    stamps: Vec<Option<SystemTime>>,
    entries: Vec<Entry>,
}

/// Who a request authenticated as.
#[derive(Debug, Clone, PartialEq)]
pub struct Identity {
    pub name: String,
    pub scopes: Vec<String>,
}

#[derive(Debug, PartialEq)]
pub enum Denied {
    /// No token, a malformed or an unknown one.
    Unauthorized,
    /// A valid token without the scope.
    Forbidden(String),
}

impl Store {
    pub fn new(files: Vec<PathBuf>) -> Self {
        let n = files.len();
        let mut store = Self {
            files,
            stamps: vec![None; n],
            entries: Vec::new(),
        };
        store.refresh();
        store
    }

    fn stamp(path: &Path) -> Option<SystemTime> {
        std::fs::metadata(path).and_then(|m| m.modified()).ok()
    }

    /// Reload when a file appeared, changed or went away.
    pub fn refresh(&mut self) {
        let stamps: Vec<_> = self.files.iter().map(|f| Self::stamp(f)).collect();
        if stamps == self.stamps && !self.entries.is_empty() {
            return;
        }
        let mut entries = Vec::new();
        for file in &self.files {
            match read_file(file) {
                Ok(f) => entries.extend(f.tokens),
                Err(e) => tracing::warn!("ignoring token file: {e}"),
            }
        }
        self.stamps = stamps;
        self.entries = entries;
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Check an `Authorization` header value for `scope`.
    pub fn authorize(&mut self, header: Option<&str>, scope: &str) -> Result<Identity, Denied> {
        self.refresh();
        let token = header
            .and_then(|h| h.strip_prefix("Bearer "))
            .map(str::trim)
            .ok_or(Denied::Unauthorized)?;
        let (id, secret) = parse(token).ok_or(Denied::Unauthorized)?;
        let hash = hash_secret(secret);
        let entry = self
            .entries
            .iter()
            .find(|e| e.id == id && constant_time_eq(e.sha256.as_bytes(), hash.as_bytes()))
            .ok_or(Denied::Unauthorized)?;
        if !entry.scopes.iter().any(|s| s == scope) {
            return Err(Denied::Forbidden(entry.name.clone()));
        }
        Ok(Identity {
            name: entry.name.clone(),
            scopes: entry.scopes.clone(),
        })
    }
}

#[derive(Subcommand, Debug)]
pub enum TokenCommand {
    /// Create a token; it is printed once and only its hash is kept.
    Create {
        /// What uses it, shown in the server's log.
        #[arg(long)]
        name: String,
        /// Repeat for several: tabs:read, tabs:control, media:control,
        /// tabs:content, tabs:capture, tabs:debug, events:read.
        #[arg(long = "scope", required = true)]
        scopes: Vec<String>,
        /// Do not save it; print the entry to put in a token file yourself
        /// (for example one managed by Nix).
        #[arg(long)]
        no_save: bool,
        /// The token file.
        #[arg(long, default_value_os_t = default_file())]
        file: PathBuf,
    },
    /// List the saved tokens (never their secrets).
    List {
        #[arg(long, default_value_os_t = default_file())]
        file: PathBuf,
        #[arg(long)]
        json: bool,
    },
    /// Revoke a saved token by name or id.
    Revoke {
        token: String,
        #[arg(long, default_value_os_t = default_file())]
        file: PathBuf,
    },
}

fn check_scopes(scopes: &[String]) -> R<()> {
    for s in scopes {
        if !SCOPES.contains(&s.as_str()) {
            return Err(format!("unknown scope {s:?} (known: {})", SCOPES.join(", ")).into());
        }
    }
    Ok(())
}

pub fn command(cmd: TokenCommand) -> R<()> {
    match cmd {
        TokenCommand::Create {
            name,
            scopes,
            no_save,
            file,
        } => {
            check_scopes(&scopes)?;
            let (token, entry) = generate(&name, &scopes)?;
            if no_save {
                println!("{token}");
                eprintln!("entry: {}", serde_json::to_string(&entry)?);
                return Ok(());
            }
            let mut f = read_file(&file)?;
            if f.tokens.iter().any(|e| e.name == name) {
                return Err(format!("a token named {name:?} exists; revoke it first").into());
            }
            f.tokens.push(entry);
            write_file(&file, &f)?;
            println!("{token}");
            Ok(())
        }
        TokenCommand::List { file, json } => {
            let f = read_file(&file)?;
            if json {
                let list: Vec<_> = f
                    .tokens
                    .iter()
                    .map(|e| serde_json::json!({"id": e.id, "name": e.name, "scopes": e.scopes, "created": e.created}))
                    .collect();
                println!("{}", serde_json::to_string_pretty(&list)?);
            } else {
                for e in &f.tokens {
                    println!("{}\t{}\t{}", e.id, e.name, e.scopes.join(","));
                }
            }
            Ok(())
        }
        TokenCommand::Revoke { token, file } => {
            let mut f = read_file(&file)?;
            let before = f.tokens.len();
            f.tokens.retain(|e| e.name != token && e.id != token);
            if f.tokens.len() == before {
                return Err(format!("no token {token:?} in {}", file.display()).into());
            }
            write_file(&file, &f)?;
            Ok(())
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn store_with(entry: Entry) -> (tempfile::TempDir, Store) {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("t.json");
        write_file(
            &path,
            &File {
                tokens: vec![entry],
            },
        )
        .unwrap();
        let store = Store::new(vec![path]);
        (dir, store)
    }

    #[test]
    fn parses_tokens_whose_secret_has_underscores() {
        assert_eq!(parse("bdl_ab12_x_y"), Some(("ab12", "x_y")));
        assert_eq!(parse("bdl__x"), None);
        assert_eq!(parse("bdl_ab12_"), None);
        assert_eq!(parse("nope_ab12_x"), None);
    }

    #[test]
    fn authorizes_by_scope() {
        let (token, entry) = generate("t", &["tabs:read".into()]).unwrap();
        let (_dir, mut store) = store_with(entry);
        let header = format!("Bearer {token}");
        assert_eq!(
            store.authorize(Some(&header), "tabs:read").unwrap().name,
            "t"
        );
        assert_eq!(
            store.authorize(Some(&header), "tabs:control"),
            Err(Denied::Forbidden("t".into()))
        );
        assert_eq!(
            store.authorize(None, "tabs:read"),
            Err(Denied::Unauthorized)
        );
        let wrong = format!("Bearer {}x", token);
        assert_eq!(
            store.authorize(Some(&wrong), "tabs:read"),
            Err(Denied::Unauthorized)
        );
    }

    #[test]
    fn reloads_after_a_revoke() {
        let (token, entry) = generate("t", &["tabs:read".into()]).unwrap();
        let (dir, mut store) = store_with(entry);
        let header = format!("Bearer {token}");
        assert!(store.authorize(Some(&header), "tabs:read").is_ok());
        let path = dir.path().join("t.json");
        // A later mtime than the first write, also on coarse file systems.
        std::thread::sleep(std::time::Duration::from_millis(20));
        write_file(&path, &File::default()).unwrap();
        let later = SystemTime::now() + std::time::Duration::from_secs(5);
        std::fs::File::options()
            .write(true)
            .open(&path)
            .unwrap()
            .set_modified(later)
            .unwrap();
        assert_eq!(
            store.authorize(Some(&header), "tabs:read"),
            Err(Denied::Unauthorized)
        );
    }

    #[test]
    fn rejects_unknown_scopes() {
        assert!(check_scopes(&["tabs:read".into()]).is_ok());
        assert!(check_scopes(&["tabs:all".into()]).is_err());
    }
}
